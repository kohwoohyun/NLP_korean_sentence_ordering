# ============================================================
# 0. 설정값
# ============================================================
MODEL_NAME    = "kakaocorp/kanana-nano-2.1b-base"

# 학습 하이퍼파라미터
NUM_EPOCHS    = 3
BATCH_SIZE    = 4
LEARNING_RATE = 2e-4
MAX_LENGTH    = 512
VAL_RATIO     = 0.2   # train 80% / val 20%

# LoRA 하이퍼파라미터
LORA_R        = 16
LORA_ALPHA    = 32
LORA_DROPOUT  = 0.05

# ============================================================
# 1. 라이브러리 임포트
# ============================================================
import os
import ast
import torch
import pandas as pd
import numpy as np
from itertools import permutations
from tqdm import tqdm
from sklearn.model_selection import train_test_split

from transformers import (
    AutoTokenizer,
    AutoModelForCausalLM,
    TrainingArguments,
    Trainer,
    DataCollatorForLanguageModeling,
    EarlyStoppingCallback,
    BitsAndBytesConfig
)
from peft import (
    LoraConfig,
    get_peft_model,
    TaskType,
    prepare_model_for_kbit_training
)
from datasets import Dataset

print("라이브러리 임포트 완료")
print(f"PyTorch 버전: {torch.__version__}")
print(f"GPU 사용 가능: {torch.cuda.is_available()}")
if torch.cuda.is_available():
    print(f"GPU: {torch.cuda.get_device_name(0)}")

BASE_DIR    = os.path.dirname(os.path.abspath(__file__))
DATA_DIR    = os.path.join(BASE_DIR, "sentence_prediction")

DATA_PATH   = os.path.join(DATA_DIR, "augmented_train.csv")
TRAIN_CSV   = os.path.join(DATA_DIR, "train.csv")
OUTPUT_DIR  = os.path.join(DATA_DIR, "output", "kanana-qlora")
RESULT_PATH = os.path.join(DATA_DIR, "results", "experiments.csv")

os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(os.path.dirname(RESULT_PATH), exist_ok=True)

# ============================================================
# 2. 데이터 로드 및 분리
# ============================================================
print("\n=== 데이터 로드 ===")

aug_df = pd.read_csv(DATA_PATH)
print(f"증강 데이터 전체: {len(aug_df)}개")

# 정답 순서만 학습에 사용
# is_correct=1인 것만 → 7351개
# 또는 전체 176424개 사용 가능
correct_df = aug_df[aug_df['is_correct'] == 1].reset_index(drop=True)
print(f"정답 순서 데이터: {len(correct_df)}개")

# train / val 분리
train_df, val_df = train_test_split(
    correct_df,
    test_size=VAL_RATIO,
    random_state=42
)
print(f"학습 데이터: {len(train_df)}개")
print(f"검증 데이터: {len(val_df)}개")

# ============================================================
# 3. 프롬프트 생성 함수
# ============================================================
def make_prompt(row):
    """
    입력:  sentence_0~3 (섞인 문장)
    출력:  올바른 순서 (answer_str)

    프롬프트 형식:
    다음 4개의 문장을 자연스러운 순서로 배열하세요.
    문장0: ...
    문장1: ...
    문장2: ...
    문장3: ...
    올바른 순서: 2 0 3 1
    """
    prompt = (
        f"다음 4개의 문장을 자연스러운 순서로 배열하세요.\n"
        f"문장0: {row['sentence_0']}\n"
        f"문장1: {row['sentence_1']}\n"
        f"문장2: {row['sentence_2']}\n"
        f"문장3: {row['sentence_3']}\n"
        f"올바른 순서: {row['answer_str']}"
    )
    return prompt

# 프롬프트 예시 확인
print("\n=== 프롬프트 예시 ===")
print(make_prompt(train_df.iloc[0]))

# ============================================================
# 4. 모델 및 토크나이저 로드
# ============================================================
print(f"\n=== 모델 로드: {MODEL_NAME} ===")

bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.float16,
    bnb_4bit_use_double_quant=True
)

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

base_model = AutoModelForCausalLM.from_pretrained(
    MODEL_NAME,
    quantization_config=bnb_config,
    device_map="auto"
)
base_model = prepare_model_for_kbit_training(base_model)
print("베이스 모델 로드 완료!")

# ============================================================
# 5. LoRA 어댑터 설정
# ============================================================
lora_config = LoraConfig(
    task_type=TaskType.CAUSAL_LM,
    r=LORA_R,
    lora_alpha=LORA_ALPHA,
    lora_dropout=LORA_DROPOUT,
    target_modules=["q_proj", "v_proj", "k_proj", "o_proj"]
)

model = get_peft_model(base_model, lora_config)
model.print_trainable_parameters()

# ============================================================
# 6. 데이터셋 토크나이징
# ============================================================
def tokenize(df):
    prompts = [make_prompt(row) for _, row in df.iterrows()]
    tokenized = tokenizer(
        prompts,
        truncation=True,
        max_length=MAX_LENGTH,
        padding="max_length",
        return_tensors="pt"
    )
    tokenized["labels"] = tokenized["input_ids"].clone()
    return Dataset.from_dict({
        "input_ids"     : tokenized["input_ids"].tolist(),
        "attention_mask": tokenized["attention_mask"].tolist(),
        "labels"        : tokenized["labels"].tolist()
    })

print("\n=== 데이터셋 토크나이징 ===")
train_dataset = tokenize(train_df)
val_dataset   = tokenize(val_df)
print(f"학습 데이터셋: {len(train_dataset)}개")
print(f"검증 데이터셋: {len(val_dataset)}개")

# ============================================================
# 7. 학습 설정
# ============================================================
training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,

    # 학습 기본 설정
    num_train_epochs=NUM_EPOCHS,
    per_device_train_batch_size=BATCH_SIZE,
    per_device_eval_batch_size=BATCH_SIZE,
    learning_rate=LEARNING_RATE,

    # Early Stopping 설정
    eval_strategy="steps",
    eval_steps=100,
    save_strategy="steps",
    save_steps=100,
    load_best_model_at_end=True,
    metric_for_best_model="eval_loss",

    # 최적화
    gradient_accumulation_steps=4,
    warmup_ratio=0.03,
    lr_scheduler_type="cosine",
    fp16=True,

    # 로깅
    logging_steps=50,
    report_to="none",

    # 저장
    save_total_limit=2
)

# ============================================================
# 8. Trainer 설정 및 학습
# ============================================================
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=val_dataset,
    data_collator=DataCollatorForLanguageModeling(
        tokenizer=tokenizer,
        mlm=False
    ),
    callbacks=[
        EarlyStoppingCallback(early_stopping_patience=3)
    ]
)

print("\n=== 학습 시작 ===")
print(f"총 에폭: {NUM_EPOCHS}")
print(f"배치 크기: {BATCH_SIZE}")
print(f"학습률: {LEARNING_RATE}")
print(f"Early Stopping: 3번 연속 개선 없으면 중단\n")

