print("\n=== 파인튜닝 후 정확도 평가 ===")

# 원본 train.csv 로드
train_orig = pd.read_csv(TRAIN_CSV)

# val 데이터의 원본 ID 기반으로 평가
val_ids = val_df['original_id'].tolist()
eval_df = train_orig[train_orig['ID'].isin(val_ids)].reset_index(drop=True)

def calc_ppl(text):
    inputs = tokenizer(
        text,
        return_tensors="pt",
        truncation=True,
        max_length=MAX_LENGTH
    ).to(model.device)
    with torch.no_grad():
        outputs = model(**inputs, labels=inputs["input_ids"])
    return torch.exp(outputs.loss).item()

def find_best_order(sentences, separator=" "):
    best_ppl   = float('inf')
    best_order = None
    for perm in permutations(range(4)):
        text = separator.join([sentences[i] for i in perm])
        ppl  = calc_ppl(text)
        if ppl < best_ppl:
            best_ppl   = ppl
            best_order = list(perm)
    return best_order

# 평가
correct = 0

for _, row in tqdm(eval_df.iterrows(), total=len(eval_df)):
    sentences = [row['sentence_0'], row['sentence_1'],
                 row['sentence_2'], row['sentence_3']]
    answer    = [int(row['answer_0']), int(row['answer_1']),
                 int(row['answer_2']), int(row['answer_3'])]
    pred      = find_best_order(sentences)
    if pred == answer:
        correct += 1

acc_after = correct / len(eval_df)
print(f"\n파인튜닝 후 정확도: {acc_after:.4f} ({correct}/{len(eval_df)})")
print(f"파인튜닝 전 정확도: 0.7628 (kanana 베이스라인)")
print(f"성능 변화: {acc_after - 0.7628:+.4f}")

