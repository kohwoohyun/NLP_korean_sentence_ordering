"""
Stage 3 — Qwen-14B QLoRA 파인튜닝 (Kanana-v2 스타일 최적화)
환경: DGX Spark (aarch64, Ubuntu)
모델: Qwen/Qwen3-14B (또는 Qwen/Qwen2.5-14B)
"""

# ============================================================
# 0. 설정값
# ============================================================
MODEL_NAME    = "Qwen/Qwen3-14B"

# 학습 하이퍼파라미터 (14B 모델에 맞춰 조정)
NUM_EPOCHS    = 3
BATCH_SIZE    = 8       # 메모리 확보를 위해 4로 조정
GRAD_ACCUM    = 2       # 실질 배치 사이즈 = 4 * 4 = 16
LEARNING_RATE = 5e-5    # Kanana-v2에서 성공한 학습률
MAX_LENGTH    = 256
VAL_RATIO     = 0.2

# LoRA 하이퍼파라미터
LORA_R        = 16
LORA_ALPHA    = 32
LORA_DROPOUT  = 0.05

# ============================================================
# 1. 라이브러리 임포트 및 경로 설정
# ============================================================
import os
import re
import torch
import pandas as pd
import numpy as np
from itertools import permutations
from tqdm import tqdm
from sklearn.model_selection import train_test_split

from transformers import (
    AutoTokenizer,
    AutoModelForCausalLM,
    TrainingArguments,
    Trainer,
    DataCollatorForLanguageModeling,
    EarlyStoppingCallback,
    BitsAndBytesConfig
)
from peft import (
    LoraConfig,
    get_peft_model,
    TaskType,
    prepare_model_for_kbit_training
)
from datasets import Dataset

# 경로 설정
BASE_DIR    = os.path.dirname(os.path.abspath(__file__))
DATA_DIR    = os.path.join(BASE_DIR, "sentence_prediction")
DATA_PATH   = os.path.join(DATA_DIR, "augmented_train.csv")
TRAIN_CSV   = os.path.join(DATA_DIR, "train.csv")
OUTPUT_DIR  = os.path.join(DATA_DIR, "output", "qwen3-14b-qlora-v2")
RESULT_PATH = os.path.join(DATA_DIR, "results", "experiments.csv")

os.makedirs(OUTPUT_DIR, exist_ok=True)

# ============================================================
# 2. 데이터 로드 (Kanana-v2와 동일한 로직)
# ============================================================
print("\n=== 데이터 로드 ===")
aug_df = pd.read_csv(DATA_PATH)

correct_df = aug_df[aug_df['is_correct'] == 1].reset_index(drop=True)
train_orig_ids, val_orig_ids = train_test_split(
    correct_df['original_id'].unique(),
    test_size=VAL_RATIO,
    random_state=42
)

train_df = aug_df[
    (aug_df['original_id'].isin(train_orig_ids)) &
    (aug_df['is_correct'] == 1)
].reset_index(drop=True)

val_df   = aug_df[
    (aug_df['original_id'].isin(val_orig_ids)) &
    (aug_df['is_correct'] == 1)
].reset_index(drop=True)

print(f"학습 데이터: {len(train_df)}개 / 검증 데이터: {len(val_df)}개")

# ============================================================
# 3. 프롬프트 생성 함수 (Kanana-v2 스타일)
# ============================================================
def make_prompt(row):
    return (
        f"아래 문장들을 올바른 순서로 배열하세요.\n"
        f"[0] {row['sentence_0']}\n"
        f"[1] {row['sentence_1']}\n"
        f"[2] {row['sentence_2']}\n"
        f"[3] {row['sentence_3']}\n"
        f"정답: {row['answer_str']}"
    )

# ============================================================
# 4. 모델 및 토크나이저 로드 (14B 최적화)
# ============================================================
print(f"\n=== 모델 로드: {MODEL_NAME} ===")
bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.bfloat16,
    bnb_4bit_use_double_quant=True
)

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

model = AutoModelForCausalLM.from_pretrained(
    MODEL_NAME,
    quantization_config=bnb_config,
    device_map="auto",
    trust_remote_code=True
)
model = prepare_model_for_kbit_training(model)

# ============================================================
# 5. LoRA 어댑터 설정 (Qwen 전용 모듈 타겟팅)
# ============================================================
lora_config = LoraConfig(
    task_type=TaskType.CAUSAL_LM,
    r=LORA_R,
    lora_alpha=LORA_ALPHA,
    lora_dropout=LORA_DROPOUT,
    target_modules=["q_proj", "v_proj", "k_proj", "o_proj"])
model = get_peft_model(model, lora_config)

# ============================================================
# 6. 토크나이징 및 데이터셋 생성
# ============================================================
def tokenize_func(df):
    prompts = [make_prompt(row) for _, row in df.iterrows()]
    tokenized = tokenizer(prompts, truncation=True, max_length=MAX_LENGTH, padding="max_length")
    return Dataset.from_dict({
        "input_ids": tokenized["input_ids"],
        "attention_mask": tokenized["attention_mask"],
        "labels": tokenized["input_ids"]
    })

train_dataset = tokenize_func(train_df)
val_dataset   = tokenize_func(val_df)

# ============================================================
# 7. 학습 설정 (TrainingArguments)
# ============================================================
training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,
    num_train_epochs=NUM_EPOCHS,
    per_device_train_batch_size=BATCH_SIZE,
    per_device_eval_batch_size=BATCH_SIZE,
    gradient_accumulation_steps=GRAD_ACCUM,
    learning_rate=LEARNING_RATE,
    eval_strategy="steps",
    eval_steps=100,
    save_strategy="steps",
    save_steps=100,
    load_best_model_at_end=True,
    metric_for_best_model="eval_loss",
    lr_scheduler_type="cosine",
    warmup_ratio=0.03,
    fp16=False,
    bf16=True,
    logging_steps=50,
    report_to="none",
    save_total_limit=2
)

# ============================================================
# 8. Trainer 실행
# ============================================================
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=val_dataset,
    data_collator=DataCollatorForLanguageModeling(tokenizer=tokenizer, mlm=False),
    callbacks=[EarlyStoppingCallback(early_stopping_patience=3)]
)

print("\n=== 학습 시작 ===")
trainer.train()
model.eval()

# ============================================================
# 9. 파인튜닝 후 정확도 평가 (Generation 방식)
# ============================================================
print("\n=== 파인튜닝 후 정확도 평가 (Generation) ===")
train_orig = pd.read_csv(TRAIN_CSV)
eval_df_orig = train_orig[train_orig['ID'].isin(val_orig_ids)].reset_index(drop=True)

def make_input_prompt(row):
    return (
        f"아래 문장들을 올바른 순서로 배열하세요.\n"
        f"[0] {row['sentence_0']}\n"
        f"[1] {row['sentence_1']}\n"
        f"[2] {row['sentence_2']}\n"
        f"[3] {row['sentence_3']}\n"
        f"정답:"
    )

def predict_order(row):
    prompt = make_input_prompt(row)
    inputs = tokenizer(prompt, return_tensors="pt", truncation=True, max_length=MAX_LENGTH).to(model.device)
    with torch.no_grad():
        outputs = model.generate(**inputs, max_new_tokens=10, do_sample=False, pad_token_id=tokenizer.eos_token_id)

    result = tokenizer.decode(outputs[0], skip_special_tokens=True)
    order_str = result.split("정답:")[-1].strip()
    try:
        numbers = re.findall(r'\d+', order_str)
        order = [int(x) for x in numbers[:4]]
        if sorted(order) == [0, 1, 2, 3]: return order
        else: return [0, 1, 2, 3]
    except: return [0, 1, 2, 3]

correct = 0
for _, row in tqdm(eval_df_orig.iterrows(), total=len(eval_df_orig)):
    answer = [int(row[f'answer_{i}']) for i in range(4)]
    pred = predict_order(row)
    if pred == answer: correct += 1

acc_after = correct / len(eval_df_orig)
print(f"\n파인튜닝 후 정확도 : {acc_after:.4f}")

# ============================================================
# 10. 결과 저장 및 모델 저장
# ============================================================
new_result = pd.DataFrame({'model': [f"{MODEL_NAME}-QLoRA-v2-Gen"], 'separator': ["' '"], 'accuracy': [acc_after]})
if os.path.exists(RESULT_PATH):
    existing = pd.read_csv(RESULT_PATH)
    pd.concat([existing, new_result], ignore_index=True).to_csv(RESULT_PATH, index=False)
else:
    new_result.to_csv(RESULT_PATH, index=False)

model.save_pretrained(f"{OUTPUT_DIR}/final")
tokenizer.save_pretrained(f"{OUTPUT_DIR}/final")
print("모든 작업 완료!")
