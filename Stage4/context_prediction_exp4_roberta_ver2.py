# ============================================================
# 0. 설정값
# ============================================================
MODEL_NAME  = "klue/roberta-large"
TRAIN_CSV   = "./sentence_prediction/train.csv"
RESULT_PATH = "./sentence_prediction/results/experiments.csv"
OUTPUT_DIR  = "./sentence_prediction/output/roberta-ordering-ver2"

NUM_EPOCHS    = 3
BATCH_SIZE    = 32
LEARNING_RATE = 2e-5
MAX_LENGTH    = 128
VAL_RATIO     = 0.2

# ============================================================
# 1. 라이브러리 임포트
# ============================================================
import os
import torch
import torch.nn as nn
import pandas as pd
import numpy as np
from itertools import permutations
from tqdm import tqdm
from sklearn.model_selection import train_test_split
from torch.utils.data import Dataset, DataLoader
from transformers import AutoTokenizer, AutoModel
from torch.optim import AdamW
from transformers import get_cosine_schedule_with_warmup

print("라이브러리 임포트 완료")
print(f"GPU: {torch.cuda.get_device_name(0)}")

os.makedirs(OUTPUT_DIR, exist_ok=True)

# ============================================================
# 2. 데이터 로드
# ============================================================
print("\n=== 데이터 로드 ===")
train_df = pd.read_csv(TRAIN_CSV)

train_ids, val_ids = train_test_split(
    train_df['ID'].tolist(),
    test_size=VAL_RATIO,
    random_state=42
)
train_data = train_df[train_df['ID'].isin(train_ids)].reset_index(drop=True)
val_data   = train_df[train_df['ID'].isin(val_ids)].reset_index(drop=True)

print(f"학습: {len(train_data)}개 / 검증: {len(val_data)}개")

# ============================================================
# 3. 토크나이저 로드
# ============================================================
tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)

# ============================================================
# 4. 데이터셋 클래스
# ============================================================
class OrderingDataset(Dataset):
    def __init__(self, df, tokenizer, max_length):
        self.data      = df
        self.tokenizer = tokenizer
        self.max_length = max_length
        self.samples   = self._build_pairs()

    def _build_pairs(self):
        """
        정답 vs 오답 쌍으로 구성
        → MarginRankingLoss에 맞는 형태
        """
        pairs = []
        for _, row in self.data.iterrows():
            sentences = [
                row['sentence_0'], row['sentence_1'],
                row['sentence_2'], row['sentence_3']
            ]
            correct = [
                int(row['answer_0']), int(row['answer_1']),
                int(row['answer_2']), int(row['answer_3'])
            ]

            correct_text = f" {self.tokenizer.sep_token} ".join(
                [sentences[i] for i in correct]
            )

            # 전체 23개 → 랜덤 5개만 샘플링
            wrong_perms = [
                list(p) for p in permutations(range(4))
                if list(p) != correct
            ]
            # 랜덤 5개 선택
            import random
            sampled_wrongs = random.sample(wrong_perms, 5)

            for wrong in sampled_wrongs:
                wrong_text = f" {self.tokenizer.sep_token} ".join(
                    [sentences[i] for i in wrong]
                )
                pairs.append({
                    'correct_text': correct_text,
                    'wrong_text'  : wrong_text
                })
        return pairs

    def __len__(self):
        return len(self.samples)

    def __getitem__(self, idx):
        sample = self.samples[idx]

        correct_enc = self.tokenizer(
            sample['correct_text'],
            max_length=self.max_length,
            padding='max_length',
            truncation=True,
            return_tensors='pt'
        )
        wrong_enc = self.tokenizer(
            sample['wrong_text'],
            max_length=self.max_length,
            padding='max_length',
            truncation=True,
            return_tensors='pt'
        )

        return {
            'correct_input_ids'     : correct_enc['input_ids'].squeeze(),
            'correct_attention_mask': correct_enc['attention_mask'].squeeze(),
            'wrong_input_ids'       : wrong_enc['input_ids'].squeeze(),
            'wrong_attention_mask'  : wrong_enc['attention_mask'].squeeze(),
        }

# ============================================================
# 5. 모델 정의
# ============================================================
class SentenceOrderingModel(nn.Module):
    def __init__(self, model_name):
        super().__init__()
        self.encoder = AutoModel.from_pretrained(model_name)
        hidden_size  = self.encoder.config.hidden_size

        # Regression Head
        self.regressor = nn.Sequential(
            nn.Linear(hidden_size, 256),
            nn.ReLU(),
            nn.Dropout(0.1),
            nn.Linear(256, 1)
        )

    def forward(self, input_ids, attention_mask):
        outputs    = self.encoder(
            input_ids=input_ids,
            attention_mask=attention_mask
        )
        # [CLS] 토큰의 hidden state 사용
        cls_output = outputs.last_hidden_state[:, 0, :]
        score      = self.regressor(cls_output).squeeze(-1)
        return score

# ============================================================
# 6. 학습 함수
# ============================================================
def train_epoch(model, loader, optimizer, scheduler, device):
    model.train()
    total_loss = 0
    criterion  = nn.MarginRankingLoss(margin=1.0)

    for batch in tqdm(loader, desc="학습 중"):
        correct_ids  = batch['correct_input_ids'].to(device)
        correct_mask = batch['correct_attention_mask'].to(device)
        wrong_ids    = batch['wrong_input_ids'].to(device)
        wrong_mask   = batch['wrong_attention_mask'].to(device)

        optimizer.zero_grad()

        correct_score = model(correct_ids, correct_mask)
        wrong_score   = model(wrong_ids, wrong_mask)

        # "정답 점수 > 오답 점수" 학습
        target = torch.ones(correct_score.size()).to(device)
        loss   = criterion(correct_score, wrong_score, target)

        loss.backward()
        nn.utils.clip_grad_norm_(model.parameters(), 1.0)
        optimizer.step()
        scheduler.step()

        total_loss += loss.item()

    return total_loss / len(loader)
# ============================================================
# 7. 정확도 평가 함수
# ============================================================
def evaluate(model, df, tokenizer, device, max_length):
    model.eval()
    correct = 0

    for _, row in tqdm(df.iterrows(), total=len(df), desc="평가 중"):
        sentences = [
            row['sentence_0'], row['sentence_1'],
            row['sentence_2'], row['sentence_3']
        ]
        answer = [
            int(row['answer_0']), int(row['answer_1']),
            int(row['answer_2']), int(row['answer_3'])
        ]

        # 24가지 순열 전부 점수 계산
        best_score = float('-inf')
        best_order = None

        for perm in permutations(range(4)):
            text = f" {tokenizer.sep_token} ".join(
                [sentences[i] for i in perm]
            )
            encoding = tokenizer(
                text,
                max_length=max_length,
                padding='max_length',
                truncation=True,
                return_tensors='pt'
            )

            with torch.no_grad():
                score = model(
                    encoding['input_ids'].to(device),
                    encoding['attention_mask'].to(device)
                ).item()

            if score > best_score:
                best_score = score
                best_order = list(perm)

        if best_order == answer:
            correct += 1

    return correct / len(df)

# ============================================================
# 8. 학습 실행
# ============================================================
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# 데이터셋 & 로더
train_dataset = OrderingDataset(train_data, tokenizer,
                                MAX_LENGTH)
train_loader  = DataLoader(train_dataset, batch_size=BATCH_SIZE,
                           shuffle=True, num_workers=4)

# 모델
model = SentenceOrderingModel(MODEL_NAME).to(device)
print(f"\n모델 파라미터: {sum(p.numel() for p in model.parameters()):,}")

# 옵티마이저 & 스케줄러
optimizer = AdamW(model.parameters(), lr=LEARNING_RATE,
                  weight_decay=0.01)
total_steps    = len(train_loader) * NUM_EPOCHS
warmup_steps   = int(total_steps * 0.1)
scheduler      = get_cosine_schedule_with_warmup(
    optimizer,
    num_warmup_steps=warmup_steps,
    num_training_steps=total_steps
)

print(f"\n=== 학습 시작 ===")
print(f"에폭: {NUM_EPOCHS} / 배치: {BATCH_SIZE} / LR: {LEARNING_RATE}")

best_acc  = 0
best_path = f"{OUTPUT_DIR}/best_model.pt"

for epoch in range(NUM_EPOCHS):
    print(f"\n--- Epoch {epoch+1}/{NUM_EPOCHS} ---")

    # 학습
    train_loss = train_epoch(model, train_loader,
                             optimizer, scheduler, device)
    print(f"Train Loss: {train_loss:.4f}")

    # 검증
    val_acc = evaluate(model, val_data, tokenizer,
                       device, MAX_LENGTH)
    print(f"Val Accuracy: {val_acc:.4f}")

    # 최고 모델 저장
    if val_acc > best_acc:
        best_acc = val_acc
        torch.save(model.state_dict(), best_path)
        print(f"최고 모델 저장! acc: {best_acc:.4f}")

# ============================================================
# 9. 최고 모델로 최종 평가
# ============================================================
print("\n=== 최종 평가 ===")
model.load_state_dict(torch.load(best_path))

final_acc = evaluate(model, val_data, tokenizer,
                     device, MAX_LENGTH)
print(f"최종 정확도: {final_acc:.4f}")
print(f"PPL 베이스라인 대비: {final_acc - 0.7628:+.4f}")

# ============================================================
# 10. 결과 저장
# ============================================================
new_result = pd.DataFrame({
    'model'    : [f"{MODEL_NAME}-Regression-Margin"],
    'separator': ["[SEP]"],
    'accuracy' : [final_acc]
})

if os.path.exists(RESULT_PATH):
    existing   = pd.read_csv(RESULT_PATH)
    result_df  = pd.concat([existing, new_result],
                           ignore_index=True)
else:
    result_df  = new_result

result_df.to_csv(RESULT_PATH, index=False)
print(f"\n결과 저장 완료!")
print(result_df)