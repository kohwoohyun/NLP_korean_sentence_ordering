# ============================================================
# 0. 설정값
# ============================================================
MODEL_NAME    = "kakaocorp/kanana-nano-2.1b-base"

# 학습 하이퍼파라미터
NUM_EPOCHS    = 3
BATCH_SIZE    = 8
LEARNING_RATE = 5e-5
MAX_LENGTH    = 256
VAL_RATIO     = 0.2   # train 80% / val 20%

# LoRA 하이퍼파라미터
LORA_R        = 16
LORA_ALPHA    = 32
LORA_DROPOUT  = 0.05

# ============================================================
# 1. 라이브러리 임포트
# ============================================================
import os
import ast
import torch
import pandas as pd
import numpy as np
from itertools import permutations
from tqdm import tqdm
from sklearn.model_selection import train_test_split

from transformers import (
    AutoTokenizer,
    AutoModelForCausalLM,
    TrainingArguments,
    Trainer,
    DataCollatorForLanguageModeling,
    EarlyStoppingCallback,
    BitsAndBytesConfig
)
from peft import (
    LoraConfig,
    get_peft_model,
    TaskType,
    prepare_model_for_kbit_training
)
from datasets import Dataset

print("라이브러리 임포트 완료")
print(f"PyTorch 버전: {torch.__version__}")
print(f"GPU 사용 가능: {torch.cuda.is_available()}")
if torch.cuda.is_available():
    print(f"GPU: {torch.cuda.get_device_name(0)}")

BASE_DIR    = os.path.dirname(os.path.abspath(__file__))
DATA_DIR    = os.path.join(BASE_DIR, "sentence_prediction")

DATA_PATH   = os.path.join(DATA_DIR, "augmented_train.csv")
TRAIN_CSV   = os.path.join(DATA_DIR, "train.csv")
OUTPUT_DIR  = os.path.join(DATA_DIR, "output", "kanana-qlora-v2")
RESULT_PATH = os.path.join(DATA_DIR, "results", "experiments.csv")

os.makedirs(OUTPUT_DIR, exist_ok=True)
os.makedirs(os.path.dirname(RESULT_PATH), exist_ok=True)

# ============================================================
# 2. 데이터 로드 및 분리
# ============================================================
print("\n=== 데이터 로드 ===")

aug_df = pd.read_csv(DATA_PATH)
print(f"증강 데이터 전체: {len(aug_df)}개")

correct_df = aug_df[aug_df['is_correct'] == 1].reset_index(drop=True)
train_orig_ids, val_orig_ids = train_test_split(
    correct_df['original_id'].unique(),
    test_size=VAL_RATIO,
    random_state=42
)

# 학습: 전체 순열 중 train ID에 해당하는 것
train_df = aug_df[
    (aug_df['original_id'].isin(train_orig_ids)) &
    (aug_df['is_correct'] == 1)
].reset_index(drop=True)

# 검증: 정답만, val ID에 해당하는 것
val_df   = aug_df[
    (aug_df['original_id'].isin(val_orig_ids)) &
    (aug_df['is_correct'] == 1)
].reset_index(drop=True)

print(f"학습 데이터: {len(train_df)}개")
print(f"검증 데이터: {len(val_df)}개")

# ============================================================
# 3. 프롬프트 생성 함수
# ============================================================
def make_prompt(row):
    """
    입력:  sentence_0~3 (섞인 문장)
    출력:  올바른 순서 (answer_str)

    프롬프트 형식:
    아래 문장들을 올바른 순서로 배열하세요.
    0: ...
    1: ...
    2: ...
    3: ...
    정담: 2 0 3 1
    """
    prompt = (
        f"아래 문장들을 올바른 순서로 배열하세요.\n"
        f"[0] {row['sentence_0']}\n"
        f"[1] {row['sentence_1']}\n"
        f"[2] {row['sentence_2']}\n"
        f"[3] {row['sentence_3']}\n"
        f"정답: {row['answer_str']}"
    )
    return prompt

# 프롬프트 예시 확인
print("\n=== 프롬프트 예시 ===")
print(make_prompt(train_df.iloc[0]))

# ============================================================
# 4. 모델 및 토크나이저 로드
# ============================================================
print(f"\n=== 모델 로드: {MODEL_NAME} ===")

bnb_config = BitsAndBytesConfig(
    load_in_4bit=True,
    bnb_4bit_quant_type="nf4",
    bnb_4bit_compute_dtype=torch.float16,
    bnb_4bit_use_double_quant=True
)

tokenizer = AutoTokenizer.from_pretrained(MODEL_NAME)
if tokenizer.pad_token is None:
    tokenizer.pad_token = tokenizer.eos_token

base_model = AutoModelForCausalLM.from_pretrained(
    MODEL_NAME,
    quantization_config=bnb_config,
    device_map="auto"
)
base_model = prepare_model_for_kbit_training(base_model)
print("베이스 모델 로드 완료!")

# ============================================================
# 5. LoRA 어댑터 설정
# ============================================================
lora_config = LoraConfig(
    task_type=TaskType.CAUSAL_LM,
    r=LORA_R,
    lora_alpha=LORA_ALPHA,
    lora_dropout=LORA_DROPOUT,
    target_modules=["q_proj", "v_proj", "k_proj", "o_proj"]
)

model = get_peft_model(base_model, lora_config)
model.print_trainable_parameters()

# ============================================================
# 6. 데이터셋 토크나이징
# ============================================================
def tokenize(df):
    prompts = [make_prompt(row) for _, row in df.iterrows()]
    tokenized = tokenizer(
        prompts,
        truncation=True,
        max_length=MAX_LENGTH,
        padding="max_length",
        return_tensors="pt"
    )
    tokenized["labels"] = tokenized["input_ids"].clone()
    return Dataset.from_dict({
        "input_ids"     : tokenized["input_ids"].tolist(),
        "attention_mask": tokenized["attention_mask"].tolist(),
        "labels"        : tokenized["labels"].tolist()
    })

print("\n=== 데이터셋 토크나이징 ===")
train_dataset = tokenize(train_df)
val_dataset   = tokenize(val_df)
print(f"학습 데이터셋: {len(train_dataset)}개")
print(f"검증 데이터셋: {len(val_dataset)}개")

# ============================================================
# 7. 학습 설정
# ============================================================
training_args = TrainingArguments(
    output_dir=OUTPUT_DIR,

    # 학습 기본 설정
    num_train_epochs=NUM_EPOCHS,
    per_device_train_batch_size=BATCH_SIZE,
    per_device_eval_batch_size=BATCH_SIZE,
    learning_rate=LEARNING_RATE,

    # Early Stopping 설정
    eval_strategy="steps",
    eval_steps=100,
    save_strategy="steps",
    save_steps=100,
    load_best_model_at_end=True,
    metric_for_best_model="eval_loss",

    # 최적화
    gradient_accumulation_steps=2,
    warmup_ratio=0.03,
    lr_scheduler_type="cosine",
    fp16=True,

    # 로깅
    logging_steps=50,
    report_to="none",

    # 저장
    save_total_limit=2
)

# ============================================================
# 8. Trainer 설정 및 학습
# ============================================================
trainer = Trainer(
    model=model,
    args=training_args,
    train_dataset=train_dataset,
    eval_dataset=val_dataset,
    data_collator=DataCollatorForLanguageModeling(
        tokenizer=tokenizer,
        mlm=False
    ),
    callbacks=[
        EarlyStoppingCallback(early_stopping_patience=3)
    ]
)

print("\n=== 학습 시작 ===")
print(f"총 에폭: {NUM_EPOCHS}")
print(f"배치 크기: {BATCH_SIZE}")
print(f"학습률: {LEARNING_RATE}")
print(f"Early Stopping: 3번 연속 개선 없으면 중단\n")

trainer.train()   # ← 주석 해제
model.eval()
print("\n학습 완료!")

# ============================================================
# 9. 파인튜닝 후 정확도 평가 (프롬프트 방식)
# ============================================================
import re

train_orig   = pd.read_csv(TRAIN_CSV)
val_orig_ids = val_df['original_id'].tolist()
eval_df_orig = train_orig[
    train_orig['ID'].isin(val_orig_ids)
].reset_index(drop=True)

def make_input_prompt(row):
    return (
        f"아래 문장들을 올바른 순서로 배열하세요.\n"
        f"[0] {row['sentence_0']}\n"
        f"[1] {row['sentence_1']}\n"
        f"[2] {row['sentence_2']}\n"
        f"[3] {row['sentence_3']}\n"
        f"정답:"
    )

def predict_order(row):
    prompt = make_input_prompt(row)
    inputs = tokenizer(
        prompt,
        return_tensors="pt",
        truncation=True,
        max_length=MAX_LENGTH
    ).to(model.device)

    with torch.no_grad():
        outputs = model.generate(
            **inputs,
            max_new_tokens=10,
            do_sample=False,
            pad_token_id=tokenizer.eos_token_id
        )

    result    = tokenizer.decode(outputs[0], skip_special_tokens=True)
    order_str = result.split("정답:")[-1].strip()

    try:
        numbers = re.findall(r'\d+', order_str)
        order   = [int(x) for x in numbers[:4]]
        if sorted(order) == [0, 1, 2, 3]:
            return order
        else:
            return [0, 1, 2, 3]
    except:
        return [0, 1, 2, 3]

correct    = 0
parse_fail = 0

for _, row in tqdm(eval_df_orig.iterrows(), total=len(eval_df_orig)):
    answer = [int(row['answer_0']), int(row['answer_1']),
              int(row['answer_2']), int(row['answer_3'])]
    pred   = predict_order(row)

    if pred == [0, 1, 2, 3] and answer != [0, 1, 2, 3]:
        parse_fail += 1
    if pred == answer:
        correct += 1

acc_after = correct / len(eval_df_orig)
print(f"\n파인튜닝 후 정확도 : {acc_after:.4f} ({correct}/{len(eval_df_orig)})")
print(f"파인튜닝 전 정확도 : 0.7628")
print(f"성능 변화          : {acc_after - 0.7628:+.4f}")
print(f"파싱 실패 횟수     : {parse_fail}개")

# ============================================================
# 10. 결과 저장
# ============================================================
result_df = pd.DataFrame({
    'model'    : [f"{MODEL_NAME}-QLoRA-v2-prompt"],
    'separator': ["' '"],
    'accuracy' : [acc_after],
})

if os.path.exists(RESULT_PATH):
    existing  = pd.read_csv(RESULT_PATH)
    result_df = pd.concat([existing, result_df], ignore_index=True)

result_df.to_csv(RESULT_PATH, index=False)
print(f"\n결과 저장 완료: {RESULT_PATH}")
print(result_df)

# ============================================================
# 11. 모델 저장
# ============================================================
model.save_pretrained(f"{OUTPUT_DIR}/final")
tokenizer.save_pretrained(f"{OUTPUT_DIR}/final")
print(f"\n모델 저장 완료: {OUTPUT_DIR}/final")